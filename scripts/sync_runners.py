#!/usr/bin/env python3
"""Generate supabase/seed/runners.sql from the `runner` project manifests.

The `runners` table tells the database which runners exist, their limits and
their fixed demo parameters. The manifests stay the source of truth; this script
turns them into one re-runnable SQL file.

    python scripts/sync_runners.py          # rewrite the file
    python scripts/sync_runners.py --check  # CI: fail if the file is out of date

Apply it by pasting supabase/seed/runners.sql into the Supabase SQL editor.
A runner is enabled only when its manifest says `status: live`.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase" / "seed" / "runners.sql"


def literal(value: str | None) -> str:
    """SQL string literal with quotes doubled (values come from our own manifests)."""
    return "null" if value is None else "'" + value.replace("'", "''") + "'"


def build() -> str:
    rows = []
    for manifest in sorted((ROOT / "projects").glob("*/project.yaml")):
        data = yaml.safe_load(manifest.read_text())
        if data.get("type") != "runner":
            continue
        runner = data["runner"]
        live = data["status"] == "live"
        demo = runner.get("demo", {})
        rows.append(
            "  ({slug}, {enabled}, {demo_enabled}, {params}::jsonb, {timeout}, {attempts}, {provider}, {digest})".format(
                slug=literal(manifest.parent.name),
                enabled=str(live).lower(),
                demo_enabled=str(live and demo.get("enabled", True)).lower(),
                params=literal(json.dumps(demo.get("params", {}), sort_keys=True)),
                timeout=int(runner.get("timeout_seconds", 120)),
                attempts=int(runner.get("max_attempts", 2)),
                provider=literal(runner.get("key_provider")),
                digest=literal(hashlib.sha256(manifest.read_bytes()).hexdigest()[:16]),
            )
        )
    return (
        "-- GENERATED by scripts/sync_runners.py from projects/*/project.yaml. Do not edit by hand.\n"
        "-- Safe to run again: existing rows are updated.\n"
        "insert into public.runners\n"
        "  (slug, enabled, demo_enabled, demo_params, timeout_seconds, max_attempts, key_provider, manifest_hash)\n"
        "values\n" + ",\n".join(rows) + "\n"
        "on conflict (slug) do update set\n"
        "  enabled = excluded.enabled, demo_enabled = excluded.demo_enabled, demo_params = excluded.demo_params,\n"
        "  timeout_seconds = excluded.timeout_seconds, max_attempts = excluded.max_attempts,\n"
        "  key_provider = excluded.key_provider, manifest_hash = excluded.manifest_hash, updated_at = now();\n"
    )


def main() -> int:
    sql = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != sql:
            print("supabase/seed/runners.sql is out of date: run python scripts/sync_runners.py")
            return 1
        print("runners.sql is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
